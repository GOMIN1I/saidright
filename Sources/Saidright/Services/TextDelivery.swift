import AppKit
import ApplicationServices
import Carbon
import SaidrightCore

/// Remembers the focused field when recording starts and delivers text only there.
/// Reports what actually happened: verified insertion, unverifiable paste, or a copy fallback.
@MainActor final class TextDelivery {
    /// The focused element captured at session start, kept for identity comparison.
    private var capturedElement: AXUIElement?
    private var capturedPID: pid_t = 0
    /// The field the last delivery pasted into and when the paste finished (instant insert).
    private var deliveredElement: AXUIElement?
    private var deliveredAt = Date.distantPast

    /// The last app other than Saidright that was active, for "Insert into …" after a button dictation.
    private(set) var lastExternalApp: NSRunningApplication?
    private var activationObserver: NSObjectProtocol?

    init() {
        if let app = NSWorkspace.shared.frontmostApplication, app.bundleIdentifier != Bundle.main.bundleIdentifier { lastExternalApp = app }
        activationObserver = NSWorkspace.shared.notificationCenter.addObserver(forName: NSWorkspace.didActivateApplicationNotification, object: nil, queue: .main) { [weak self] note in
            guard let app = note.userInfo?[NSWorkspace.applicationUserInfoKey] as? NSRunningApplication, app.bundleIdentifier != Bundle.main.bundleIdentifier else { return }
            MainActor.assumeIsolated { self?.lastExternalApp = app }
        }
    }

    /// Destination for a dictation started inside Saidright: the previous app, never pasted automatically.
    func lastExternalDestination() -> DestinationInfo? {
        guard let app = lastExternalApp, !app.isTerminated else { return nil }
        return DestinationInfo(processID: app.processIdentifier, bundleID: app.bundleIdentifier, appName: app.localizedName ?? "App", elementToken: nil, isSecureField: false)
    }

    /// Captures the frontmost app and its focused element. Call before showing any UI.
    func captureDestination() -> DestinationInfo? {
        guard let app = NSWorkspace.shared.frontmostApplication, app.bundleIdentifier != Bundle.main.bundleIdentifier else {
            capturedElement = nil
            capturedPID = 0
            return nil
        }
        capturedPID = app.processIdentifier
        capturedElement = focusedElement()
        let secure = capturedElement.map(isSecure) ?? false
        return DestinationInfo(processID: app.processIdentifier, bundleID: app.bundleIdentifier, appName: app.localizedName ?? app.bundleIdentifier ?? "App", elementToken: capturedElement.map { Int(CFHash($0)) }, isSecureField: secure || IsSecureEventInputEnabled())
    }

    /// Delivers `text` into the captured destination.
    func deliver(_ text: String, html: String? = nil, to destination: DestinationInfo?, restoreClipboard: Bool) async -> DeliveryOutcome {
        guard let destination else { copy(text); return .copied(reason: .noDestination) }
        guard let app = NSRunningApplication(processIdentifier: destination.processID), !app.isTerminated else { copy(text); return .copied(reason: .noDestination) }
        if destination.isSecureField || IsSecureEventInputEnabled() { copy(text); return .copied(reason: .secureInput) }
        guard AXIsProcessTrusted() || CGPreflightPostEventAccess() else { copy(text); return .copied(reason: .noPostPermission) }

        // Focus must still be where it was. If the person switched apps or fields, do not paste.
        guard NSWorkspace.shared.frontmostApplication?.processIdentifier == destination.processID else { copy(text); return .copied(reason: .focusChanged) }
        let current = focusedElement()
        if destination.elementToken != nil, let captured = capturedElement, let current, !sameField(captured, current) { copy(text); return .copied(reason: .focusChanged) }

        let before = current.flatMap(value)
        let pasteboard = NSPasteboard.general
        let saved = restoreClipboard ? snapshot(pasteboard) : []
        pasteboard.clearContents()
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        // Apps that paste formatted text take this instead: real tables and lists.
        if let html { item.setString(html, forType: .html) }
        // Ask clipboard managers not to record this temporary content.
        item.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.TransientType"))
        item.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"))
        pasteboard.writeObjects([item])
        let ourChange = pasteboard.changeCount

        postCommandV()

        // Verify through Accessibility when the field exposes its value.
        var verified = false
        if let element = current ?? focusedElement(), before != nil || value(element) != nil {
            for _ in 0..<12 {
                try? await Task.sleep(for: .milliseconds(50))
                if let after = value(element), after != before, after.contains(text.prefix(200)) { verified = true; break }
            }
        } else {
            try? await Task.sleep(for: .milliseconds(250))
        }

        if restoreClipboard {
            // Give slow apps time to read the clipboard before restoring it.
            try? await Task.sleep(for: .milliseconds(verified ? 150 : 700))
            if pasteboard.changeCount == ourChange {
                pasteboard.clearContents()
                if !saved.isEmpty { pasteboard.writeObjects(saved) }
            }
        }
        deliveredElement = current ?? focusedElement()
        deliveredAt = Date()
        return verified ? .insertedVerified(app: destination.appName) : .insertedUnverified(app: destination.appName)
    }

    /// Instant insert: replaces the transcript that `deliver` just pasted with the edited text.
    /// Only when nothing happened in between — no key press or click since the paste, the same
    /// app and field focused — and, where the field shows its contents, the transcript is still
    /// there with the cursor right after it. The edit is written through Accessibility into that
    /// field only (no second paste); fields that hide their contents keep the transcript.
    func replaceDelivered(_ old: String, with new: String, html: String? = nil, destination: DestinationInfo, restoreClipboard: Bool, strict: Bool = true) async -> Bool {
        func skip(_ reason: String) -> Bool { Log.info("instant replace skipped: \(reason)"); return false }
        guard let element = deliveredElement, old != new, !old.isEmpty else { return skip("nothing delivered") }
        guard NSWorkspace.shared.frontmostApplication?.processIdentifier == destination.processID else { return skip("app changed") }
        guard let current = focusedElement(), sameField(element, current) else { return skip("field changed") }
        let quiet = Date().timeIntervalSince(deliveredAt) - 0.05
        // A person's own request (the card's "Replace" button) is itself a click; it only needs the
        // text to still be in the field.
        for type in strict ? [CGEventType.keyDown, .leftMouseDown, .rightMouseDown, .otherMouseDown] : [] {
            if CGEventSource.secondsSinceLastEventType(.combinedSessionState, eventType: type) < quiet { return skip("input since paste (\(type.rawValue))") }
        }
        if let text = value(current) {
            // The field shows its contents: select exactly the pasted transcript and replace it.
            let ns = text as NSString
            let found = ns.range(of: old, options: .backwards)
            guard found.location != NSNotFound else { return skip("transcript not in field") }
            guard let caret = selectedRange(current), !strict || (caret.length == 0 && caret.location == found.location + found.length) else { return skip("cursor moved (\(String(describing: selectedRange(current))) vs end \(found.location + found.length))") }
            var range = CFRange(location: found.location, length: found.length)
            guard let axRange = AXValueCreate(.cfRange, &range), AXUIElementSetAttributeValue(current, kAXSelectedTextRangeAttribute as CFString, axRange) == .success else { return skip("cannot select") }
            try? await Task.sleep(for: .milliseconds(30))
            guard selectedRange(current).map({ $0.location == found.location && $0.length == found.length }) == true else { return skip("selection not applied") }
            // Paste over the selection with Cmd+V sent to the destination process itself, so the
            // keystroke cannot reach whatever other window happens to be in front.
            await paste(new, html: html, to: destination.processID, restoreClipboard: restoreClipboard)
            for _ in 0..<16 {
                // Formatted pastes (HTML tables) read back without the text markup: then the
                // transcript being gone is the sign that the paste landed.
                if let after = value(current), after != text, after.contains(new.prefix(200)) || (html != nil && !after.contains(old)), !after.contains(old) || new.contains(old) { deliveredAt = Date(); return true }
                try? await Task.sleep(for: .milliseconds(40))
            }
            // Not replaced: put the cursor back after the transcript instead of leaving it selected.
            var end = strict ? CFRange(location: found.location + found.length, length: 0) : caret
            if let caretValue = AXValueCreate(.cfRange, &end) { AXUIElementSetAttributeValue(current, kAXSelectedTextRangeAttribute as CFString, caretValue) }
            return skip("edit not found in the field")
        }
        // Fields that hide their contents cannot be checked: the transcript stays.
        return skip("field hides its contents")
    }

    private func paste(_ text: String, html: String?, to pid: pid_t, restoreClipboard: Bool) async {
        let pasteboard = NSPasteboard.general
        let saved = restoreClipboard ? snapshot(pasteboard) : []
        pasteboard.clearContents()
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        if let html { item.setString(html, forType: .html) }
        item.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.TransientType"))
        item.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"))
        pasteboard.writeObjects([item])
        let ourChange = pasteboard.changeCount
        let source = CGEventSource(stateID: .privateState)
        let v = CGKeyCode(kVK_ANSI_V)
        for down in [true, false] {
            let event = CGEvent(keyboardEventSource: source, virtualKey: v, keyDown: down)
            event?.flags = .maskCommand
            event?.postToPid(pid)
        }
        try? await Task.sleep(for: .milliseconds(300))
        if restoreClipboard {
            try? await Task.sleep(for: .milliseconds(400))
            if pasteboard.changeCount == ourChange {
                pasteboard.clearContents()
                if !saved.isEmpty { pasteboard.writeObjects(saved) }
            }
        }
    }

    private func selectedRange(_ element: AXUIElement) -> CFRange? {
        var value: CFTypeRef?
        guard AXUIElementCopyAttributeValue(element, kAXSelectedTextRangeAttribute as CFString, &value) == .success, let value, CFGetTypeID(value) == AXValueGetTypeID() else { return nil }
        var range = CFRange()
        return AXValueGetValue(value as! AXValue, .cfRange, &range) ? range : nil
    }

    func copy(_ text: String) {
        NSPasteboard.general.clearContents()
        NSPasteboard.general.setString(text, forType: .string)
    }

    private func postCommandV() {
        let source = CGEventSource(stateID: .combinedSessionState)
        let v = CGKeyCode(kVK_ANSI_V)
        let down = CGEvent(keyboardEventSource: source, virtualKey: v, keyDown: true)
        let up = CGEvent(keyboardEventSource: source, virtualKey: v, keyDown: false)
        down?.flags = .maskCommand
        up?.flags = .maskCommand
        down?.post(tap: .cghidEventTap)
        up?.post(tap: .cghidEventTap)
    }

    private func snapshot(_ pasteboard: NSPasteboard) -> [NSPasteboardItem] {
        (pasteboard.pasteboardItems ?? []).map { item in
            let copy = NSPasteboardItem()
            for type in item.types { if let data = item.data(forType: type) { copy.setData(data, forType: type) } }
            return copy
        }
    }

    // MARK: Accessibility helpers

    private func focusedElement() -> AXUIElement? {
        guard AXIsProcessTrusted() else { return nil }
        let system = AXUIElementCreateSystemWide()
        var value: CFTypeRef?
        guard AXUIElementCopyAttributeValue(system, kAXFocusedUIElementAttribute as CFString, &value) == .success, let value, CFGetTypeID(value) == AXUIElementGetTypeID() else { return nil }
        return (value as! AXUIElement)
    }

    private func value(_ element: AXUIElement) -> String? {
        var value: CFTypeRef?
        guard AXUIElementCopyAttributeValue(element, kAXValueAttribute as CFString, &value) == .success else { return nil }
        return value as? String
    }

    /// Some apps (browsers, Electron) hand out a new element object for the same field;
    /// fall back to comparing role, window and frame.
    private func sameField(_ a: AXUIElement, _ b: AXUIElement) -> Bool {
        if CFEqual(a, b) { return true }
        func attr(_ e: AXUIElement, _ name: String) -> CFTypeRef? {
            var v: CFTypeRef?
            return AXUIElementCopyAttributeValue(e, name as CFString, &v) == .success ? v : nil
        }
        guard let roleA = attr(a, kAXRoleAttribute) as? String, roleA == attr(b, kAXRoleAttribute) as? String else { return false }
        if let wa = attr(a, kAXWindowAttribute), let wb = attr(b, kAXWindowAttribute), !CFEqual(wa, wb) { return false }
        for name in [kAXPositionAttribute, kAXSizeAttribute] {
            if let va = attr(a, name), let vb = attr(b, name), !CFEqual(va, vb) { return false }
        }
        return true
    }

    private func isSecure(_ element: AXUIElement) -> Bool {
        var role: CFTypeRef?
        AXUIElementCopyAttributeValue(element, kAXSubroleAttribute as CFString, &role)
        return (role as? String) == (kAXSecureTextFieldSubrole as String)
    }
}
